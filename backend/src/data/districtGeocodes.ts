// Build lookup maps for fast matching
const _normalize = (s: string) => s.toLowerCase().trim().replace(/[^a-z0-9]/g, "");
const byKey: Map<string, DistrictGeo> = new Map();
for (const d of DISTRICT_GEOCODES) {
  byKey.set(`${_normalize(d.state)}|${_normalize(d.name)}`, d);
  // Also add alias keys for common variations
  byKey.set(`${_normalize(d.name)}`, d);
}

export function findDistrict(state: string, district: string): DistrictGeo | null {
  if (!state && !district) return null;
  const s = _normalize(state || "");
  const d = _normalize(district || "");
  return byKey.get(`${s}|${d}`) || byKey.get(d) || null;
}

export function findByDistrictName(name: string): DistrictGeo | null {
  return byKey.get(_normalize(name)) || null;
}
