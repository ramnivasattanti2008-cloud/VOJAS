function lookup(name: string): { lat: number; lng: number } | null {
  if (!name) return null;
  const upper = name.toUpperCase().trim();
  if (COORDS[upper]) return COORDS[upper];
  // Strip common suffixes
  const stripped = upper
    .replace(/\s+(DISTRICT|TOWN|CITY|URBAN|RURAL|NORTH|SOUTH|EAST|WEST|CENTRAL)$/, "")
    .trim();
  if (COORDS[stripped]) return COORDS[stripped];
  // Try without the word "DISTRICT"
  const noDistrict = upper.replace(/\s+DISTRICT$/, "").trim();
  if (COORDS[noDistrict]) return COORDS[noDistrict];
  return null;
}

